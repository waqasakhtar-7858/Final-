import os
import numpy as np

from flask      import Flask, request, jsonify
from tensorflow import keras
from PIL        import Image

# ============================================================
# SECTION 1: App Configuration
# ============================================================

app = Flask(__name__)

# ---- Uploads folder -----------------------------------------
# ChestXrayProject/backend/uploads/
UPLOAD_FOLDER = os.path.join(os.path.dirname(__file__), 'uploads')
os.makedirs(UPLOAD_FOLDER, exist_ok=True)

app.config['UPLOAD_FOLDER'] = UPLOAD_FOLDER

# ---- Allowed image formats ----------------------------------
ALLOWED_EXTENSIONS = {'jpg', 'jpeg', 'png', 'bmp'}

# ---- Image size (must match training) -----------------------
IMG_SIZE = (224, 224)

# ---- Class names in alphabetical order (must match training)-
# IMPORTANT: This order must match exactly what flow_from_directory
# assigned during training. It assigns labels alphabetically.
CLASS_NAMES = [
    'Bengin cases',       # index 0
    'Malignant cases',    # index 1
    'Normal cases',       # index 2
    'Pneumonia',          # index 3
    'Tuberclosis',        # index 4
    'covid'               # index 5
]

# ---- Friendly display names ---------------------------------
CLASS_DISPLAY_NAMES = {
    'Bengin cases'   : 'Benign Cancer',
    'Malignant cases': 'Malignant Cancer',
    'Normal cases'   : 'Normal',
    'Pneumonia'      : 'Pneumonia',
    'Tuberclosis'    : 'Tuberculosis',
    'covid'          : 'COVID-19'
}

# ============================================================
# SECTION 2: Load the Model
# ============================================================
# Model is loaded once when server starts.
# ChestXrayProject/model/best_model.h5

MODEL_PATH = os.path.join(
    os.path.dirname(__file__),   # ChestXrayProject/backend/
    '..',                         # go up to ChestXrayProject/
    'model',
    'best_model.h5'
)

print("Loading model... please wait.")

try:
    model = keras.models.load_model(MODEL_PATH)
    print(f"Model loaded successfully.")
    print(f"  Path          : {MODEL_PATH}")
    print(f"  Input shape   : {model.input_shape}")
    print(f"  Output shape  : {model.output_shape}")
except Exception as e:
    print(f"ERROR: Could not load model.")
    print(f"  Reason : {e}")
    print(f"  Fix    : Make sure best_model.h5 is inside ChestXrayProject/model/")
    model = None

