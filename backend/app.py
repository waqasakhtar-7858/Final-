@app.route('/', methods=['GET'])
def home():
    """
    Home route. Confirms server is running.
    Visit: http://localhost:5000
    """
    return jsonify({
        'project' : 'ChestXrayProject',
        'message' : 'Respiratory Disease Detection API is running.',
        'usage'   : 'POST an image to /predict to get a diagnosis.',
        'classes' : list(CLASS_DISPLAY_NAMES.values())
    })


@app.route('/health', methods=['GET'])
def health():
    """
    Health check route.
    Visit: http://localhost:5000/health
    """
    return jsonify({
        'project'     : 'ChestXrayProject',
        'status'      : 'running',
        'model_loaded': model is not None,
        'classes'     : CLASS_NAMES,
        'input_size'  : '224x224'
    })


@app.route('/predict', methods=['POST'])
def predict():
    """
    Prediction endpoint.
    Send a POST request with an image file (key: 'file').
    Returns predicted disease and confidence score.
    """

    # ---- Step 1: Check model is loaded ----------------------
    if model is None:
        return jsonify({
            'status' : 'error',
            'message': 'Model not loaded. Check server logs.'
        }), 500

    # ---- Step 2: Check file was sent ------------------------
    if 'file' not in request.files:
        return jsonify({
            'status' : 'error',
            'message': 'No file found. Send image with key name: file'
        }), 400

    file = request.files['file']

    # ---- Step 3: Check file is not empty --------------------
    if file.filename == '':
        return jsonify({
            'status' : 'error',
            'message': 'No file selected.'
        }), 400

    # ---- Step 4: Check file extension -----------------------
    if not allowed_file(file.filename):
        return jsonify({
            'status' : 'error',
            'message': 'File type not allowed.',
            'allowed': list(ALLOWED_EXTENSIONS)
        }), 400

    # ---- Step 5: Save file temporarily ----------------------
    saved_path = os.path.join(app.config['UPLOAD_FOLDER'], file.filename)
    file.save(saved_path)

    # ---- Step 6: Preprocess image ---------------------------
    try:
        img_array = preprocess_image(saved_path)
    except Exception as e:
        return jsonify({
            'status' : 'error',
            'message': f'Image processing failed. Reason: {str(e)}'
        }), 500

    # ---- Step 7: Run prediction -----------------------------
    try:
        predictions     = model.predict(img_array, verbose=0)
        predicted_index = int(np.argmax(predictions[0]))
        confidence      = float(predictions[0][predicted_index]) * 100
        predicted_class = CLASS_NAMES[predicted_index]
        disease_name    = CLASS_DISPLAY_NAMES[predicted_class]

        all_probs = {
            CLASS_DISPLAY_NAMES[CLASS_NAMES[i]]: round(float(predictions[0][i]) * 100, 2)
            for i in range(len(CLASS_NAMES))
        }

    except Exception as e:
        return jsonify({
            'status' : 'error',
            'message': f'Prediction failed. Reason: {str(e)}'
        }), 500

    # ---- Step 8: Delete temp file ---------------------------
    try:
        os.remove(saved_path)
    except Exception:
        pass

    # ---- Step 9: Return JSON result -------------------------
    return jsonify({
        'status'           : 'success',
        'predicted_class'  : predicted_class,
        'disease'          : disease_name,
        'confidence'       : round(confidence, 2),
        'all_probabilities': all_probs
    })


